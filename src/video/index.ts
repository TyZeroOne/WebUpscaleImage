export * from './types'

/**
 * Единственный переключатель видео-функциональности.
 *
 * Когда появится реализация, достаточно поменять значение здесь: все точки
 * расширения спрашивают именно этот флаг, а не проверяют наличие модуля.
 */
export const VIDEO_ENHANCEMENT_ENABLED = false

export type VideoBadgeMode = 'hidden' | 'disabled' | 'interactive'

/**
 * Как показывать плашку над видео.
 *
 * РЕШЕНИЕ ЭТАПА 9: в публикуемой сборке — 'hidden'.
 *
 * На этапе 8 плашка рендерилась в состоянии 'disabled' с пометкой «скоро».
 * Для разработки это было правильно: позиционирование, хит-тест сквозь слой
 * управления плеера и поведение при прокрутке проверены на живом элементе,
 * и будущему этапу остаётся только логика.
 *
 * Но в расширении, которое устанавливает посторонний человек, надпись «скоро»
 * — это обещание без срока. Пользователь либо ждёт напрасно, либо решает,
 * что расширение недоделано. Ни то, ни другое не стоит выигрыша от того,
 * что кто-то заранее узнает о планах.
 *
 * Код плашки при этом остаётся на месте и продолжает собираться: вернуть её
 * — одно значение здесь.
 */
export function videoBadgeMode(): VideoBadgeMode {
  return VIDEO_ENHANCEMENT_ENABLED ? 'interactive' : 'hidden'
}

/**
 * Минимальная сторона видео, ниже которой плашка не показывается.
 *
 * То же соображение, что и с картинками: на маленьком превью плашка займёт
 * половину площади и перекроет содержимое. Порог тот же, 64 px.
 */
export const MIN_VIDEO_SIDE_PX = 64

/**
 * ЧТО ПРИДЁТСЯ СДЕЛАТЬ БУДУЩЕМУ ЭТАПУ
 *
 * Заготовки, оставленные здесь, покрывают только форму данных. Ниже — конкретные
 * препятствия, выясненные за этапы 0-7. Все они относятся к реализации, и ни одно
 * не решается тем, что уже написано.
 *
 * 1. ОТКУДА БРАТЬ КАДРЫ.
 *    Прочитать кадры из <video> на странице можно через drawImage в canvas,
 *    но это работает в реальном времени и только для видимого воспроизведения:
 *    минуту видео пришлось бы проигрывать минуту. Быстрый путь — WebCodecs
 *    (VideoDecoder), но ему нужен сам файл, а не элемент страницы.
 *
 * 2. ГДЕ ЕГО СКАЧИВАТЬ.
 *    На этапе 7 выяснилось, что двоичные данные ходят между content script
 *    и service worker только текстом (base64 через JSON). Для картинки в мегабайт
 *    это приемлемо, для видео в сотни мегабайт — нет. Значит, скачивать
 *    и обрабатывать видео придётся целиком в одном контексте расширения,
 *    то есть в offscreen-документе, который до сих пор не понадобился ни разу.
 *
 * 3. ЧТО С ПОТОКОВЫМ ВИДЕО.
 *    Большинство крупных площадок отдают видео не файлом, а сегментами через
 *    Media Source Extensions. У <video> в таком случае src вида blob:, и скачать
 *    по нему нечего — отсюда отказ 'no-source-url'. Разбор HLS/DASH-манифестов
 *    это отдельная задача, сопоставимая по объёму со всем текущим проектом.
 *
 * 4. DRM.
 *    Защищённые потоки (Netflix и подобные) недоступны технически и не должны
 *    быть доступны: обход DRM — не то, что делает расширение для улучшения
 *    картинок. Отказ 'protected' здесь окончательный.
 *
 * 5. СТОИМОСТЬ.
 *    Замеры этапа 5: кадр 1200×900 на WebGPU — 496 мс. Минута видео 30 fps —
 *    1800 кадров, то есть около 15 минут работы при идеальном железе.
 *    На WASM это часы. Обрабатывать целые ролики бессмысленно; отсюда
 *    диапазон в VideoEnhanceOptions и обязательная оценка перед запуском.
 *
 * 6. УПАКОВКА ОБРАТНО.
 *    Улучшенные кадры нужно собрать в файл. WebCodecs даёт VideoEncoder,
 *    но контейнер (MP4/WebM) он не пишет — нужен либо свой мультиплексор,
 *    либо ffmpeg.wasm, который весит больше, чем всё текущее расширение.
 *
 * ЧТО ИЗ УЖЕ НАПИСАННОГО ПЕРЕИСПОЛЬЗУЕТСЯ БЕЗ ИЗМЕНЕНИЙ
 *
 *  - core/enhance/ — апскейл одного кадра это и есть апскейл картинки;
 *  - ML-воркер с загруженной моделью: он уже единственный экземпляр,
 *    держащий модель между вызовами, — ровно то, что нужно для потока кадров;
 *  - обработка плитками из этапа 5 — кадр 4K иначе не пройдёт по лимитам WebGPU;
 *  - очередь из этапа 3: задача там это просто асинхронная функция,
 *    кадры лягут в неё как есть;
 *  - панель прогресса — VideoProgress специально описан в кадрах, а не булевым
 *    «готово/не готово», чтобы панель не переписывать.
 */
