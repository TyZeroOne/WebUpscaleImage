import { resampleLanczos } from './lanczos'

/**
 * Сохранение прозрачности при обработке нейросетью.
 *
 * ПОЧЕМУ ЭТО ВООБЩЕ НУЖНО
 *
 * Модели увеличения принимают вход формы [1, H, W, 3] — три канала, RGB.
 * Альфы там нет и быть не может: их учили на фотографиях, а у фотографии
 * прозрачности не бывает. При чтении картинки tf.browser.fromPixels молча
 * отбрасывает четвёртый канал, а tf.browser.toPixels так же молча возвращает
 * альфу равной 255.
 *
 * Результат: логотип с прозрачным фоном после нейросети получает фон
 * непрозрачный — обычно чёрный, потому что в отброшенных пикселях RGB
 * как раз нули. На веб-странице это заметно сразу и выглядит как поломка.
 *
 * Классический путь (фильтр Ланцоша) этой болезнью не страдает: он считает
 * все четыре канала и учитывает предумножение на альфу.
 *
 * КАК ЧИНИМ
 *
 * Альфа обрабатывается ОТДЕЛЬНО от цвета: снимается с оригинала до модели,
 * масштабируется до размера результата и возвращается на место после.
 *
 * Масштабируется она фильтром Ланцоша, а не моделью — модель её принять
 * не может. Потери в этом почти нет: альфа в реальных картинках либо
 * ступенчатая (вырезанный объект), либо плавная (тень, градиент), и в обоих
 * случаях синтезировать в ней нечего. Придумывать детали осмысленно
 * в текстуре, а не в маске прозрачности.
 */

/**
 * Альфа-канал, снятый с картинки, в виде обычного ImageData.
 *
 * Значение альфы продублировано в R, G и B, а сам альфа-канал выставлен
 * в 255. Так плоскость можно прогнать через тот же resampleLanczos, что
 * и цветную картинку, не заводя для неё отдельного одноканального пути.
 *
 * Дублирование в три канала — плата за переиспользование: втрое больше
 * работы, чем нужно теоретически. Она всё равно теряется на фоне модели,
 * а второй ресемплер пришлось бы отдельно писать и отдельно проверять.
 */
export type AlphaPlane = ImageData

/**
 * Снять альфу, если она вообще есть.
 *
 * Возвращает null для полностью непрозрачной картинки — а таких
 * подавляющее большинство. Один проход по пикселям с ранним выходом
 * дешевле, чем масштабирование заведомо однородной плоскости.
 */
export function extractAlphaPlane(image: ImageData): AlphaPlane | null {
  const { data, width, height } = image

  let transparent = false
  for (let i = 3; i < data.length; i += 4) {
    if (data[i] !== 255) {
      transparent = true
      break
    }
  }
  if (!transparent) return null

  const plane = new ImageData(width, height)
  for (let i = 0; i < data.length; i += 4) {
    const alpha = data[i + 3]!
    plane.data[i] = alpha
    plane.data[i + 1] = alpha
    plane.data[i + 2] = alpha
    plane.data[i + 3] = 255
  }
  return plane
}

/**
 * Радиус окна при масштабировании альфы.
 *
 * Тройка, а не двойка: у вырезанных объектов граница альфы — самое
 * контрастное, что есть в картинке, и мягкий фильтр превратил бы её
 * в заметную кайму. Звон Ланцоша на такой границе тоже возможен,
 * но он гасится обрезкой в 0..255, которую делает Uint8ClampedArray.
 */
const ALPHA_RADIUS = 3

/**
 * Вернуть альфу на готовый результат.
 *
 * Вызывать НУЖНО последним шагом, после сборки плиток и после маскирования:
 * маскирование альфу не трогает, но читает и пишет холст целиком, и лишний
 * проход между ними ничего бы не дал.
 */
export function applyAlphaPlane(canvas: OffscreenCanvas, plane: AlphaPlane): void {
  const context = canvas.getContext('2d', { willReadFrequently: true })
  if (!context) return

  const scaled =
    plane.width === canvas.width && plane.height === canvas.height
      ? plane
      : resampleLanczos(plane, canvas.width, canvas.height, ALPHA_RADIUS)

  const image = context.getImageData(0, 0, canvas.width, canvas.height)
  for (let i = 0; i < image.data.length; i += 4) {
    image.data[i + 3] = scaled.data[i]!
  }
  context.putImageData(image, 0, 0)
}
