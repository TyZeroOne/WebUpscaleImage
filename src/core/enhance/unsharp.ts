/**
 * Нерезкое маскирование (unsharp mask).
 *
 * Название пришло из плёночной фотографии: чтобы получить резкий отпечаток,
 * с негатива делали НЕРЕЗКУЮ копию и печатали через неё. Размытая копия
 * гасила крупные детали, оставляя мелкие — края выходили подчёркнутыми.
 *
 * В цифре то же самое одной формулой:
 *
 *     результат = оригинал + сила × (оригинал − размытый оригинал)
 *
 * Разность «оригинал минус размытие» — это в точности мелкие детали:
 * там, где картинка гладкая, размытие от неё не отличается и разность равна
 * нулю; на краях разность велика. Прибавляя её, мы усиливаем края,
 * не трогая ровные участки.
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ НЕЙРОСЕТИ
 *
 * Принципиально. Сеть ДОДУМЫВАЕТ детали, которых в файле нет, — и потому
 * может ошибиться. Нерезкое маскирование ничего не добавляет: оно только
 * усиливает перепады, которые в картинке уже есть. Выдумать оно не может
 * ничего, зато и восстановить утраченное — тоже.
 *
 * Модуль не знает ни про DOM, ни про chrome API: только ImageData на входе
 * и выходе. Поэтому работает и в воркере классического апскейла,
 * и в ML-воркере.
 */

/**
 * Радиус размытия в пикселях (ядро 5 отсчётов).
 *
 * Радиус определяет, какого масштаба детали считаются «мелкими». Единица
 * (ядро из трёх отсчётов) подчёркивает только переходы шириной в пиксель —
 * после увеличения вчетверо края занимают больше, и такой радиус их почти
 * не заметит. Двойка — компромисс: работает и по увеличенным краям,
 * и не превращает картинку в аппликацию.
 *
 * Значение не вынесено в настройки намеренно: пользователю понятна «сила»,
 * а радиус требует понимания, что именно он меняет.
 */
const RADIUS = 2

/**
 * Порог: перепады слабее не усиливаются.
 *
 * Без него маскирование одинаково усиливает и края, и шум — а на сжатой
 * картинке ещё и блоки JPEG вместе с полосами в градиентах. Порог отделяет
 * настоящие перепады от мелкой ряби.
 *
 * 4 из 255 — примерно уровень, ниже которого разница между соседними
 * пикселями глазом уже не читается как деталь.
 */
const THRESHOLD = 4

/**
 * Одномерное ядро Гаусса.
 *
 * Гаусс, а не прямоугольное усреднение: у прямоугольного размытия резкие
 * границы, и разность с ним даёт заметные ореолы вокруг краёв.
 * Сигма = радиус / 2 — обычное соотношение, при котором ядро успевает
 * затухнуть к своему краю.
 */
function gaussianKernel(radius: number): Float32Array {
  const sigma = radius / 2
  const size = radius * 2 + 1
  const kernel = new Float32Array(size)
  let sum = 0
  for (let i = 0; i < size; i++) {
    const x = i - radius
    const value = Math.exp(-(x * x) / (2 * sigma * sigma))
    kernel[i] = value
    sum += value
  }
  // Нормировка: сумма весов обязана быть единицей, иначе размытие изменит
  // яркость, и разность с ним даст сдвиг всей картинки.
  for (let i = 0; i < size; i++) kernel[i]! /= sum
  return kernel
}

/**
 * Усиление краёв на месте. Изменяет переданный ImageData.
 *
 * @param amount сила в процентах: 0 — ничего не делать, 100 — прибавить
 *               разность целиком.
 */
export function unsharpMask(image: ImageData, amount: number): void {
  if (amount <= 0) return

  const { width, height, data } = image
  const kernel = gaussianKernel(RADIUS)
  const strength = amount / 100

  /**
   * Единственный вспомогательный буфер: горизонтально размытые RGB.
   *
   * Вертикальный проход читает из него и сразу применяет формулу, записывая
   * результат обратно в data. Второй буфер (под полностью размытую копию)
   * не нужен — это экономит треть памяти на больших картинках.
   *
   * Uint8, а не float: буфер хранит уже размытые значения, то есть заведомо
   * лежащие в 0..255, и точности байта здесь достаточно.
   */
  const blurredRows = new Uint8ClampedArray(width * height * 3)

  // --- проход 1: размытие по горизонтали ------------------------------------
  for (let y = 0; y < height; y++) {
    const rowStart = y * width
    for (let x = 0; x < width; x++) {
      let r = 0
      let g = 0
      let b = 0
      for (let k = -RADIUS; k <= RADIUS; k++) {
        // Края достраиваются повтором крайнего пикселя: нули дали бы
        // тёмную кайму по периметру.
        const sx = Math.min(width - 1, Math.max(0, x + k))
        const weight = kernel[k + RADIUS]!
        const p = (rowStart + sx) * 4
        r += data[p]! * weight
        g += data[p + 1]! * weight
        b += data[p + 2]! * weight
      }
      const o = (rowStart + x) * 3
      blurredRows[o] = r
      blurredRows[o + 1] = g
      blurredRows[o + 2] = b
    }
  }

  // --- проход 2: размытие по вертикали и сразу применение формулы -----------
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      let r = 0
      let g = 0
      let b = 0
      for (let k = -RADIUS; k <= RADIUS; k++) {
        const sy = Math.min(height - 1, Math.max(0, y + k))
        const weight = kernel[k + RADIUS]!
        const p = (sy * width + x) * 3
        r += blurredRows[p]! * weight
        g += blurredRows[p + 1]! * weight
        b += blurredRows[p + 2]! * weight
      }

      const o = (y * width + x) * 4
      /**
       * Читаем исходное значение и пишем в ту же ячейку. Это безопасно:
       * размытие берётся из отдельного буфера, а не из data, поэтому
       * соседние пиксели на результат уже не влияют.
       *
       * Присваивание в Uint8ClampedArray само обрезает выход за 0..255 —
       * маскирование по своей природе даёт выбросы на контрастных краях
       * (тот самый светлый ореол).
       */
      const sr = data[o]!
      const sg = data[o + 1]!
      const sb = data[o + 2]!

      const dr = sr - r
      const dg = sg - g
      const db = sb - b

      if (Math.abs(dr) >= THRESHOLD) data[o] = sr + strength * dr
      if (Math.abs(dg) >= THRESHOLD) data[o + 1] = sg + strength * dg
      if (Math.abs(db) >= THRESHOLD) data[o + 2] = sb + strength * db
      // Альфа не трогается: прозрачность — не деталь, и её усиление
      // дало бы рваные края у картинок с прозрачным фоном.
    }
  }
}
