/**
 * Возврат управления браузеру между тяжёлыми участками работы.
 *
 * Пока вычисления идут в главном потоке (до этапа 4), это единственный способ
 * дать странице отрисоваться и обработать клики пользователя — в частности,
 * нажатие «Отмена».
 */

/**
 * Пауза, дающая браузеру отрисовать кадр.
 *
 * requestAnimationFrame срабатывает ПЕРЕД отрисовкой, поэтому одного его мало:
 * пара «rAF, затем setTimeout» возвращает управление уже после того,
 * как кадр показан.
 *
 * СТРАХОВКА ОБЯЗАТЕЛЬНА. В невидимой вкладке браузер не рисует кадры,
 * и requestAnimationFrame не вызывается вовсе — ожидание внутри него
 * не закончилось бы никогда. Без второго таймера пользователь, переключивший
 * вкладку, получил бы навсегда зависшую обработку.
 * Проверено на стенде: без страховки обработка не завершалась.
 *
 * Приём нужен до этапа 4: в Worker'е поток страницы не занят,
 * и отдавать ему кадр незачем.
 */
const PAINT_FALLBACK_MS = 50

export function yieldUntilPainted(): Promise<void> {
  return new Promise((resolve) => {
    let settled = false
    const finish = (): void => {
      if (settled) return
      settled = true
      resolve()
    }
    requestAnimationFrame(() => setTimeout(finish, 0))
    setTimeout(finish, PAINT_FALLBACK_MS)
  })
}
